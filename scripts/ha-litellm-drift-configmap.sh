#!/usr/bin/env bash
# Regenerate the ConfigMap the ha-litellm-drift CronJob (deployments/lamg/ha-litellm-drift.yaml)
# runs inside both Home Assistant pods. Rerun it after every rebase of the litellm fork, then
# commit the result: the baseline in the cluster has to be the one the installed fork came from,
# or the check alerts on a drift you already fixed (or stays green on one you did not).
#
#   ./scripts/ha-litellm-drift-configmap.sh [path/to/ha-litellm-ai-task]
#
# ha-assist.py rides along because the job uses its --ws mode to read the config entry state.
set -euo pipefail
cd "$(dirname "$0")/.."

FORK=${1:-$HOME/Documents/projects/ha-litellm-ai-task}
OUT=deployments/lamg/ha-litellm-drift-configmap.yaml

rev=$(git -C "$FORK" rev-parse --short HEAD)
git -C "$FORK" diff --quiet HEAD -- check-upstream-drift.py upstream-baseline.json || rev="$rev+uncommitted"
ver=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["ha_version"])' "$FORK/upstream-baseline.json")

{
  echo "# GENERATED by scripts/ha-litellm-drift-configmap.sh, do not edit by hand."
  echo "# Source: ha-litellm-ai-task $rev (baseline HA $ver) + scripts/ha-assist.py"
  kubectl create configmap ha-litellm-drift -n lamg --dry-run=client -o yaml \
    --from-file="$FORK/check-upstream-drift.py" \
    --from-file="$FORK/upstream-baseline.json" \
    --from-file=scripts/ha-assist.py |
    grep -v '^  creationTimestamp: null$'
} >"$OUT"
echo "wrote $OUT from fork $rev (baseline HA $ver)"
git --no-pager diff --stat -- "$OUT"
